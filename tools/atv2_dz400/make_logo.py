"""Draws the Suzuki DZ400 roster logo (logo_suzuki) for ATV Offroad Fury 2 and writes it, as a
zlib-compressed .pst texture, to ps2xRuntime/src/lib/Kernel/Atv2SuzukiDz400Logo.inc.

The disc has no Suzuki logo, so this one is drawn in the style of the retail roster logos: a 256x64
8-bit paletted texture with the brand wordmark (black, white outline) over the model name (gradient,
dark outline), right-aligned, italic.
.pst layout: u32 1, u32 1, u32 mipCount; 256 RGBA CLUT entries in PS2 CSM1 order (alpha 0..0x80);
per mip level u32 height, u32 width, u32 0, u32 0, then width*height palette indices.

usage: python make_logo.py [font.ttf]   (default: Windows Arial Black; needs Pillow)
"""
import os
import struct
import sys
import zlib

from PIL import Image, ImageDraw, ImageFilter, ImageFont

W, H = 256, 64
FONT = sys.argv[1] if len(sys.argv) > 1 else 'C:/Windows/Fonts/ariblk.ttf'
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'ps2xRuntime', 'src', 'lib', 'Kernel',
                   'Atv2SuzukiDz400Logo.inc')


def text_mask(text, size, shear, track=0):
    font = ImageFont.truetype(FONT, size)
    left, top, right, bottom = font.getbbox(text)
    height = bottom - top + 4
    mask = Image.new('L', (right - left + track * len(text) + int(height * shear) + 16, height), 0)
    draw = ImageDraw.Draw(mask)
    x = 2
    for ch in text:
        draw.text((x - left, 2 - top), ch, font=font, fill=255)
        x += font.getlength(ch) + track
    slanted = mask.transform(mask.size, Image.AFFINE, (1, shear, -shear * height, 0, 1, 0), Image.BICUBIC)
    return slanted.crop(slanted.getbbox())


def place(canvas, mask, fill, stroke, radius, right, top):
    x = right - mask.width
    grown = Image.new('L', (mask.width + 2 * radius, mask.height + 2 * radius), 0)
    grown.paste(mask, (radius, radius))
    grown = grown.filter(ImageFilter.MaxFilter(2 * radius + 1))
    canvas.paste(Image.new('RGBA', grown.size, stroke), (x - radius, top - radius), grown)
    canvas.paste(fill.resize(mask.size), (x, top), mask)


def draw_logo():
    canvas = Image.new('RGBA', (W, H), (0, 0, 0, 0))
    gradient = Image.new('RGBA', (1, 64))
    for y in range(64):
        t = y / 63
        gradient.putpixel((0, y), (255, int(232 - 70 * t), int(40 - 40 * t), 255))
    place(canvas, text_mask('SUZUKI', 23, 0.22, track=1), Image.new('RGBA', (1, 1), (12, 12, 16, 255)),
          (255, 255, 255, 255), 2, 244, 3)
    place(canvas, text_mask('DZ400', 40, 0.28), gradient, (20, 20, 30, 255), 2, 252, 25)
    return canvas


def csm1(i):  # CLUT storage order: entries 8..15 and 16..23 of each 32 swap places
    b = i & 0x18
    return (i & ~0x18) | (0x10 if b == 0x08 else 0x08 if b == 0x10 else b)


def to_pst(image):
    quantized = image.quantize(colors=256, method=Image.Quantize.FASTOCTREE)  # keeps alpha (RGBA palette)
    palette = [(0, 0, 0, 0)] * 256
    for rgba, index in quantized.palette.colors.items():
        r, g, b, a = rgba if len(rgba) == 4 else (*rgba, 255)
        palette[index] = (r, g, b, (a * 128 + 127) // 255)
    clut = bytearray(1024)
    for index, (r, g, b, a) in enumerate(palette):
        struct.pack_into('4B', clut, 4 * csm1(index), r, g, b, a)
    return (struct.pack('<3I', 1, 1, 1) + bytes(clut) + struct.pack('<4I', H, W, 0, 0) +
            bytes(quantized.getdata()))


def main():
    pst = to_pst(draw_logo())
    assert len(pst) == 0x441C
    packed = zlib.compress(pst, 9)
    lines = ['// Generated by tools/atv2_dz400/make_logo.py: logo_suzuki.pst (256x64, 8-bit), zlib.',
             f'// {len(pst)} bytes inflated.',
             'static const uint8_t kSuzukiLogoPstZlib[] = {']
    for i in range(0, len(packed), 20):
        lines.append('    ' + ', '.join(f'0x{b:02X}' for b in packed[i:i + 20]) + ',')
    lines.append('};')
    with open(OUT, 'w', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
    print(f'{OUT}: {len(pst)} -> {len(packed)} bytes')


if __name__ == '__main__':
    main()
